// Builds src/js/18-geodata.js: the outlines the globe and map draw from.
// World land is Natural Earth 1:110m; the Pacific Northwest is 1:50m; the Seattle shoreline is 1:10m
// (all public domain, through the world-atlas package). State borders are US Census (us-atlas).
// Run: cd tools && npm install && node geodata.js
const fs = require('fs'), path = require('path'), topo = require('topojson-client');
const load = p => JSON.parse(fs.readFileSync(require.resolve(p)));
const rings = (file, obj) => { const t = load(file), f = topo.feature(t, t.objects[obj]), out = []; const add = g => { if (g.type === 'Polygon') g.coordinates.forEach(r => out.push(r)); else if (g.type === 'MultiPolygon') g.coordinates.forEach(p => p.forEach(r => out.push(r))); else if (g.type === 'GeometryCollection') g.geometries.forEach(add); }; (f.features || [f]).forEach(x => add(x.geometry)); return out; };
// Sutherland-Hodgman: cut a ring to a box
function clipRing(ring, [x0, y0, x1, y1]) {
  const edges = [[p => p[0] >= x0, (a, b) => [x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0])]], [p => p[0] <= x1, (a, b) => [x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0])]],
    [p => p[1] >= y0, (a, b) => [a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0]], [p => p[1] <= y1, (a, b) => [a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1]]];
  let pts = ring.slice(0, -1);
  for (const [inside, cut] of edges) {
    const out = []; if (!pts.length) break;
    for (let i = 0; i < pts.length; i++) { const a = pts[i], b = pts[(i + 1) % pts.length], ia = inside(a), ib = inside(b); if (ia) out.push(a); if (ia !== ib) out.push(cut(a, b)); }
    pts = out;
  }
  return pts.length >= 3 ? pts.concat([pts[0]]) : null;
}
// Douglas-Peucker
function simplify(pts, tol) {
  if (pts.length < 5) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1; const stack = [[0, pts.length - 1]];
  while (stack.length) { const [a, b] = stack.pop(); let far = -1, fd = tol; const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy);
    // a closed ring starts and ends on the same point, so measure from that point instead of from a line
    for (let i = a + 1; i < b; i++) { const d = len ? Math.abs((pts[i][0] - ax) * dy - (pts[i][1] - ay) * dx) / len : Math.hypot(pts[i][0] - ax, pts[i][1] - ay); if (d > fd) { fd = d; far = i; } }
    if (far > 0) { keep[far] = 1; stack.push([a, far], [far, b]); } }
  return pts.filter((_, i) => keep[i]);
}
// one ring as whole numbers: the first point, then steps from the point before
function pack(pts, q) { const out = []; let px = 0, py = 0; pts.forEach((p, i) => { const x = Math.round(p[0] * q), y = Math.round(p[1] * q); if (i && x === px && y === py) return; out.push(i ? x - px : x, i ? y - py : y); px = x; py = y; }); return out; }
const layer = (rs, q, tol, box, minPts) => rs.map(r => box ? clipRing(r, box) : r).filter(Boolean).map(r => simplify(r, tol)).filter(r => r.length >= (minPts || 4)).map(r => pack(r, q)).filter(r => r.length >= 8);
const PNW = [-130, 39, -108, 52], SEA = [-123.4, 46.9, -121.6, 48.4];
const us = load('us-atlas/states-10m.json');
const borders = topo.mesh(us, us.objects.states, (a, b) => a !== b).coordinates.map(l => l.filter(p => p[0] >= PNW[0] && p[0] <= PNW[2] && p[1] >= PNW[1] && p[1] <= PNW[3])).filter(l => l.length > 1).map(l => pack(simplify(l, .01), 200));
const GEO = {
  land: { q: 100, r: layer(rings('world-atlas/land-110m.json', 'land'), 100, .02) },
  mid: { q: 200, box: PNW, r: layer(rings('world-atlas/land-50m.json', 'land'), 200, .012, PNW) },
  hi: { q: 2000, box: SEA, r: layer(rings('world-atlas/land-10m.json', 'land'), 2000, .0012, SEA) },
  borders: { q: 200, l: borders }
};
const count = L => (L.r || L.l).reduce((a, r) => a + r.length / 2, 0);
const js = '/* Map outlines, generated by tools/geodata.js. Do not edit by hand.\n   World land: Natural Earth 1:110m. Pacific Northwest: 1:50m. Seattle shoreline: 1:10m. State borders: US Census.\n   Each ring is whole numbers: the first point, then the step from the point before, at q units to a degree. */\nconst GEO = ' + JSON.stringify(GEO) + ';\n';
fs.writeFileSync(path.join(__dirname, '../src/js/18-geodata.js'), js);
console.log('land', GEO.land.r.length, 'rings', count(GEO.land), 'pts | mid', GEO.mid.r.length, count(GEO.mid), '| hi', GEO.hi.r.length, count(GEO.hi), '| borders', GEO.borders.l.length, count(GEO.borders), '| file', Math.round(js.length / 1024), 'KB');
